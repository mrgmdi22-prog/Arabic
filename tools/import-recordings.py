#!/usr/bin/env python3
"""Import recordings exported from studio/ (a ZIP of files named like s__lion__1.webm).

For each file: trim the silence at both ends, even out the loudness, convert to mono MP3,
and save it as audio/<key>.mp3 (key = s/lion/1). Then rewrite assets/audio.js so the site
shows a listen button wherever a recording exists.

    python3 tools/import-recordings.py marafi-recordings-20261028.zip
"""
import io, json, os, re, subprocess, sys, tempfile, time, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO = os.path.join(ROOT, 'audio')
KEY = re.compile(r'^([spwd])__([a-z0-9]+)__([a-z0-9]+)$')
FILTER = ('silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.12,'
          'areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.25,areverse,'
          'loudnorm=I=-18:TP=-2:LRA=11,afade=t=in:d=0.02')

def convert(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-af', FILTER, '-ac', '1', '-ar', '44100',
                    '-c:a', 'libmp3lame', '-b:a', '64k', dst], check=True)

def manifest():
    entries = {}
    for dirpath, _, files in os.walk(AUDIO):
        for f in files:
            if f.endswith('.mp3'):
                key = os.path.relpath(os.path.join(dirpath, f[:-4]), AUDIO).replace(os.sep, '/')
                entries[key] = int(os.path.getmtime(os.path.join(dirpath, f)))
    body = json.dumps(dict(sorted(entries.items())), ensure_ascii=False, indent=0)
    with io.open(os.path.join(ROOT, 'assets', 'audio.js'), 'w', encoding='utf-8') as fh:
        fh.write('// Recordings in the teacher\'s voice. Generated by tools/import-recordings.py — do not edit by hand.\n'
                 '// key → version (the file lives at audio/<key>.mp3)\nwindow.AUDIO = ' + body + ';\n')
    return len(entries)

def main(zips):
    done, skipped = 0, []
    with tempfile.TemporaryDirectory() as tmp:
        for zp in zips:
            with zipfile.ZipFile(zp) as z:
                for info in z.infolist():
                    stem, _ = os.path.splitext(os.path.basename(info.filename))
                    m = KEY.match(stem)
                    if not m:
                        skipped.append(info.filename); continue
                    src = os.path.join(tmp, os.path.basename(info.filename))
                    with open(src, 'wb') as out: out.write(z.read(info))
                    convert(src, os.path.join(AUDIO, m.group(1), m.group(2), m.group(3) + '.mp3'))
                    done += 1
    total = manifest()
    print(f'imported {done} recordings; {total} on the site in all')
    if skipped: print('skipped (unknown names):', ', '.join(skipped))

if __name__ == '__main__':
    if len(sys.argv) < 2: sys.exit(__doc__)
    main(sys.argv[1:])
